import { writeFile } from 'node:fs/promises';
import { GREENER_PASTURES } from '../shared/worlds/greenerPastures.mjs';
import { navigationSignature } from '../shared/worlds/navigationSignature.mjs';
import { navGraph, NAV } from '../shared/sim/botNav.mjs';
const source={...GREENER_PASTURES,navigation:{nodes:GREENER_PASTURES.navigation.nodes}};
const graph=navGraph(source),edges=[];
for(let a=0;a<graph.links.length;a++)for(const {to:b,cost} of graph.links[a])if(a<b)edges.push([a,b,cost]);
const prepared={signature:navigationSignature(source),policy:JSON.stringify(NAV),edges};
await writeFile(new URL('../shared/worlds/greenerNavigation.mjs',import.meta.url),
  '// Generated by node scripts/build-greener-navigation.mjs. Physical route tests validate every link.\n'+
  `export const GREENER_NAVIGATION = Object.freeze(${JSON.stringify(prepared)});\n`);
console.log(`Prepared ${graph.nodes.length} nodes and ${edges.length} ordinary running links.`);
